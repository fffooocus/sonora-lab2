import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import midiFile from 'midi-file';
import { createAppServer } from './serve.mjs';
import { launchBrowser } from './browser.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const server = createAppServer();
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
let browser;
const checks = [], errors = [];
const check = (name, assertion) => { assert.ok(assertion, name); checks.push(name); console.log(`PASS ${name}`); };
try {
  browser = await launchBrowser();
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(base); await page.waitForFunction(() => document.querySelector('#note-count').textContent === '24' && document.querySelector('#data-table tbody').rows.length === 24);
  check('Default dataset automatically creates 24 notes', await page.locator('#data-table tbody tr').count() === 24);
  check('Default indicators are temperature and precipitation', await page.locator('#pitch-column').inputValue() === 'temperature' && await page.locator('#expression-column').inputValue() === 'precipitation');
  await mkdir(new URL('../docs/screenshots/', import.meta.url), { recursive: true });
  await page.screenshot({ path: `${root}/docs/screenshots/studio-desktop.png`, fullPage: true });
  await page.getByRole('button', { name: 'Відтворити', exact: true }).click();
  await page.waitForTimeout(700);
  check('Web Audio starts and timeline advances', Number(await page.locator('#seek').inputValue()) > 0);
  await page.getByRole('button', { name: 'Призупинити', exact: true }).click();
  const position = await page.locator('#seek').inputValue(); await page.waitForTimeout(150);
  check('Pause preserves position', await page.locator('#seek').inputValue() === position);
  await page.getByRole('button', { name: 'Відтворити', exact: true }).click();
  await page.waitForTimeout(150); await page.getByRole('button', { name: 'Зупинити', exact: true }).click();
  check('Stop resets timeline', await page.locator('#seek').inputValue() === '0');
  await page.locator('#volume').fill('0'); await page.locator('#volume').dispatchEvent('input');
  await page.locator('#seek').fill('500'); await page.locator('#seek').dispatchEvent('input');
  check('Seek updates the current time', await page.locator('#current-time').textContent() === '00:06');
  await page.locator('#tempo').fill('120'); await page.locator('#tempo').dispatchEvent('input');
  check('Tempo updates duration and resets playback', await page.locator('#total-time').textContent() === '00:12' && await page.locator('#seek').inputValue() === '0');
  await page.locator('#instrument').selectOption('10'); await page.locator('#scale').selectOption('minor');
  const downloading = page.waitForEvent('download'); await page.locator('#download-midi').click();
  const download = await downloading, parsed = midiFile.parseMidi(await readFile(await download.path()));
  check('Downloaded MIDI reflects instrument, tempo and note count', parsed.header.numTracks === 2 && parsed.tracks[1].find(e => e.type === 'programChange').programNumber === 10 && parsed.tracks[0].find(e => e.type === 'setTempo').microsecondsPerBeat === 500000 && parsed.tracks[1].filter(e => e.type === 'noteOn').length === 24);
  await page.locator('#pitch-column').selectOption('precipitation');
  check('Mapping indicators stay distinct', await page.locator('#expression-column').inputValue() === 'temperature');
  await page.locator('#demo-energy').click(); await page.waitForFunction(() => document.querySelector('#note-count').textContent === '16');
  check('Alternative demo switches data and composition', await page.locator('#dataset-name').textContent() === 'energy.csv');
  await page.locator('#file-input').setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from('x,y\n1,NaN\n2,3') });
  check('Invalid CSV reports error and preserves previous composition', await page.locator('#data-error').isVisible() && await page.locator('#note-count').textContent() === '16');
  await page.locator('#file-input').setInputFiles(`${root}/examples/semicolon.csv`);
  check('CSV upload accepts Ukrainian headings and decimal commas', await page.locator('#note-count').textContent() === '6' && await page.locator('#pitch-column').inputValue() === 'температура');
  await page.locator('#edit-data').click(); await page.locator('#csv-editor').fill('x,y\n0,0\n10,10'); await page.locator('#apply-csv').click();
  check('CSV editor automatically regenerates MIDI', await page.locator('#note-count').textContent() === '2');
  await page.locator('#edit-data').click(); await page.locator('#csv-editor').fill('x,y\nNaN,0\n10,10'); await page.locator('#apply-csv').click();
  check('Invalid editor data stays editable with diagnostic', await page.locator('#csv-dialog').isVisible() && await page.locator('#editor-error').isVisible());
  await page.getByRole('button', { name: 'Скасувати', exact: true }).click();
  await page.locator('#file-input').setInputFiles({ name: 'safe.csv', mimeType: 'text/csv', buffer: Buffer.from('label,x,y\n<img src=x onerror=alert(1)>,1,2\nhello,3,4') });
  check('CSV labels render as text without HTML execution', await page.locator('#data-table img').count() === 0 && (await page.locator('#data-table tbody').textContent()).includes('<img'));
  await page.locator('#file-input').setInputFiles({ name: 'huge.csv', mimeType: 'text/csv', buffer: Buffer.alloc(1024 * 1024 + 1, 65) });
  check('Oversize CSV is rejected before processing', (await page.locator('#data-error').textContent()).includes('1 МБ'));
  await page.locator('#demo-weather').click(); await page.locator('#tempo').fill('108'); await page.locator('#tempo').dispatchEvent('input');
  await page.locator('#scale').selectOption('pentatonic'); await page.locator('#instrument').selectOption('11');
  await page.locator('[data-view="guide"]').click();
  check('Algorithm page opens with formulas', await page.locator('#view-guide').isVisible());
  await page.screenshot({ path: `${root}/docs/screenshots/algorithm.png`, fullPage: true });
  await page.locator('[data-view="report"]').click();
  check('Submission page includes student details', (await page.locator('#view-report').textContent()).includes('Левківський Євгеній Сергійович'));
  await page.locator('[data-view="studio"]').click();
  await page.locator('#toast').waitFor({ state: 'hidden' });
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    check(`Responsive layout has no page overflow at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    if (width === 390) await page.screenshot({ path: `${root}/docs/screenshots/studio-mobile.png`, fullPage: true });
  }
  await page.locator('body').click({ position: { x: 500, y: 15 } });
  await page.keyboard.press('Space'); await page.waitForTimeout(100);
  check('Space shortcut starts playback', (await page.locator('#play').getAttribute('aria-label')) === 'Призупинити');
  await page.keyboard.press('Escape');
  check('Escape shortcut stops playback', await page.locator('#seek').inputValue() === '0');
  check('No browser JavaScript errors', errors.length === 0);
  await writeFile(new URL('../docs/verification.json', import.meta.url), JSON.stringify({ environment: 'Playwright Chromium (local Microsoft Edge when available)', checksPassed: checks.length, checks, errors, note: 'Automated functional checks; acoustic fidelity and external DAW playback are not certified.' }, null, 2) + '\n');
  console.log(`Browser checks: ${checks.length} passed.`);
} finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)); }
